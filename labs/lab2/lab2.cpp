#include <iostream>
#include <cmath>    // Для математических функций exp(), pow(), fabs()
#include <iomanip>  // Директива для точного форматирования вывода знаков после запятой

int main()
{
    // Настройка русской локали для корректного вывода сообщений
    setlocale(LC_ALL, "ru");

    // Переменные задачи:
    double eps;          // Заданная пользователем точность вычислений (эпсилон)
    double sum = 0.0;    // Накопитель суммы членов ряда (инициализируем нулем)
    double an = 0.0;     // Значение текущего общего члена ряда a_n
    int n = 0;           // Порядковый номер слагаемого (счетчик итераций)

    std::cout << "=== ЛАБОРАТОРНАЯ РАБОТА №2 (ВАРИАНТ 20) ===\n";
    std::cout << "Ряд: a_n = e^n * 100^(-n^2)\n\n";

    // Интерактивный ввод точности с клавиатуры через консоль
    std::cout << "Введите требуемую точность eps (например, 0.0001): ";
    std::cin >> eps;

    // Проверка корректности введенного значения точности
    if (eps <= 0)
    {
        std::cout << "Ошибка: точность eps должна быть строго больше 0!\n";
        return 1;
    }

    // Итерационный процесс: вычисляем члены ряда до тех пор, 
    // пока модуль очередного слагаемого |a_n| не станет меньше eps
    do
    {
        n++; // Переход к следующему номеру слагаемого (n = 1, 2, 3...)

        // Вычисление общего члена ряда: a_n = e^n * 100^(-n^2)
        // exp(n) вычисляет e в степени n
        // pow(100.0, -1.0 * n * n) вычисляет 100 в степени (-n^2)
        an = exp(n) * pow(100.0, -1.0 * n * n);

        // Накопление текущего слагаемого в общую сумму
        sum += an;

    } while (fabs(an) >= eps); // Условие продолжения: пока текущий член не меньше точности

    // Настройка увеличенной точности вывода (8 знаков после запятой)
    std::cout << std::fixed << std::setprecision(8);

    std::cout << "\nРезультаты вычислений:\n";
    std::cout << eps << " Заданная точность eps\n";
    std::cout << sum << " Полученная сумма ряда\n";
    std::cout << an  << " Значение последнего члена ряда an\n";
    std::cout << n   << " Число выполненных итераций (n)\n";

    return 0;
}
